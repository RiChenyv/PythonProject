# print() 基础使用：输出到屏幕

# 1. 直接输出内容
print("hello world")
print("喵喵喵")
print("————————————————————————")

# 2. 输出数字
print(666)
print(3.14)
print("————————————————————————")

# 3. 输出变量
name = "richenyv"
age = 18
print(name)
print(age)
print("————————————————————————")

# 4. 一次输出多个内容（用逗号隔开，默认用空格连接）
print("我的名字是", name, "今年", age, "岁")
print("————————————————————————")

# 5. 输出表达式的结果
print(10 + 20)
print("哈哈" * 3)
print("————————————————————————")

# 6. print 默认会换行
print("第一行")
print("第二行")
